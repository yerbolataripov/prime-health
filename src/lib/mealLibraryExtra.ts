import type { GroceryGroup, MealCategory, MealPrepTemplate, MealTag } from "./types";

type Ing = MealPrepTemplate["ingredients"][number];
const g = (name: string, grams: number, group: GroceryGroup): Ing => ({ name, grams, group });
const pc = (name: string, pieces: number, group: GroceryGroup): Ing => ({ name, pieces, group });

interface Opts {
  light?: boolean;
  prep?: boolean;
  tags?: MealTag[];
  notes?: string;
}

function T(
  id: string,
  name: string,
  category: MealCategory,
  macros: [number, number, number, number, number], // ккал, белки, жиры, углеводы, клетчатка
  prepTimeMin: number,
  ingredients: Ing[],
  steps: string[],
  o: Opts = {}
): MealPrepTemplate {
  const [calories, protein, fat, carbs, fiber] = macros;
  const tags: MealTag[] = [...(o.tags ?? [])];
  if (protein >= 30 && !tags.includes("high_protein")) tags.push("high_protein");
  if (o.light && !tags.includes("light")) tags.push("light");
  return {
    id: `x-${id}`,
    name,
    category,
    ingredients,
    calories, protein, fat, carbs, fiber,
    prepTimeMin,
    light: !!o.light,
    prepFriendly: !!o.prep,
    tags,
    steps,
    notes: o.notes,
  };
}

